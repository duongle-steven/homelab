// Package crds chooses the CRDs each environment applies (docs/superpowers/specs/2026-11-25-testbed-capacity-design.md):
// the vendored CRDs (system/crds/files/<component>/) of the components its ApplicationSets deploy, and of every kind its
// renders use. The sandbox applies them all, so it has no list.
package crds

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"time"

	"go.yaml.in/yaml/v3"

	"github.com/duongle-steven/homelab/cli/internal/guard"
)

// Environments with a list; the sandbox (dev) applies every CRD
var Environments = []string{"prod", "testbed"}

const header = "# Generated by lab crds generate (system/crds/files/ paths this environment applies): do not edit\n"

// render renders a chart directory or an app file for an environment, the way Argo CD does (a test replaces it)
var render = renderChart

func renderChart(root, target, env string) ([]byte, error) {
	var err error
	// Chart downloads sometimes reset the connection: try three times
	for attempt := 0; attempt < 3; attempt++ {
		cmd := exec.Command(filepath.Join(root, "scripts", "render-chart"), target, env)
		cmd.Dir = root
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		var out []byte
		if out, err = cmd.Output(); err == nil {
			return out, nil
		}
		err = fmt.Errorf("render %s (%s): %w: %s", target, env, err, strings.TrimSpace(stderr.String()))
		if attempt < 2 {
			time.Sleep(5 * time.Second)
		}
	}
	return nil, err
}

type object struct {
	APIVersion string `yaml:"apiVersion"`
	Kind       string `yaml:"kind"`
	Spec       struct {
		Group string `yaml:"group"`
		Names struct {
			Kind string `yaml:"kind"`
		} `yaml:"names"`
	} `yaml:"spec"`
}

// documents decodes every YAML document of raw
func documents(raw []byte) ([]object, error) {
	var objs []object
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	for {
		var o object
		err := dec.Decode(&o)
		if errors.Is(err, io.EOF) {
			return objs, nil
		}
		if err != nil {
			return nil, err
		}
		objs = append(objs, o)
	}
}

// builtIn: the core group, the k8s.io groups (the Gateway API's come from k3s's manifests) and rook-ceph's csi.ceph.io,
// which ceph-csi-operator installs itself (TestEveryKindHasItsCRD's rules)
// argoCD's own CRDs come with system/argocd, which the bootstrap applies; Argo Workflows', Events' and Rollouts' kinds,
// in the same group, are vendored like any other
var argoCD = map[string]bool{"argoproj.io/Application": true, "argoproj.io/ApplicationSet": true, "argoproj.io/AppProject": true}

func builtIn(group string) bool {
	return !strings.Contains(group, ".") || strings.HasSuffix(group, ".k8s.io") || group == "csi.ceph.io"
}

// vendored maps each CRD file (relative to system/crds/files/) to its component and its group/kind
func vendored(root string) (byKind map[string]string, byComponent map[string][]string, err error) {
	byKind, byComponent = map[string]string{}, map[string][]string{}
	files, err := filepath.Glob(filepath.Join(root, "system", "crds", "files", "*", "*.yaml"))
	if err != nil {
		return nil, nil, err
	}
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return nil, nil, err
		}
		objs, err := documents(raw)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", f, err)
		}
		rel, _ := filepath.Rel(filepath.Join(root, "system", "crds", "files"), f)
		rel = filepath.ToSlash(rel)
		for _, o := range objs {
			if o.Kind == "CustomResourceDefinition" {
				byKind[o.Spec.Group+"/"+o.Spec.Names.Kind] = rel
			}
		}
		component := strings.SplitN(rel, "/", 2)[0]
		byComponent[component] = append(byComponent[component], rel)
	}
	return byKind, byComponent, nil
}

// targets is what an environment renders: the deployed chart directories under system/ and platform/, the apps, and
// the fixed sources the root template adds to every Application (egress and the SecretStore in production)
func targets(root, env string) (components, all []string, err error) {
	d, err := guard.ReadDeployed(root, env)
	if err != nil {
		return nil, nil, err
	}
	charts, err := filepath.Glob(filepath.Join(root, "*", "*", "Chart.yaml"))
	if err != nil {
		return nil, nil, err
	}
	for _, c := range charts {
		dir, _ := filepath.Rel(root, filepath.Dir(c))
		dir = filepath.ToSlash(dir)
		if (strings.HasPrefix(dir, "system/") || strings.HasPrefix(dir, "platform/")) && d.Deploys(dir) {
			components = append(components, dir)
		}
	}
	all = append(all, components...)
	for _, pattern := range d.Apps {
		apps, err := filepath.Glob(filepath.Join(root, pattern))
		if err != nil {
			return nil, nil, err
		}
		for _, a := range apps {
			rel, _ := filepath.Rel(root, a)
			all = append(all, filepath.ToSlash(rel))
		}
	}
	return components, append(all, d.Sources...), nil
}

// Lists is, for each environment with a list, the sorted CRD files it applies
func Lists(root string) (map[string][]string, error) {
	byKind, byComponent, err := vendored(root)
	if err != nil {
		return nil, err
	}
	lists := map[string][]string{}
	for _, env := range Environments {
		components, all, err := targets(root, env)
		if err != nil {
			return nil, err
		}
		chosen := map[string]bool{}
		for _, c := range components {
			for _, f := range byComponent[filepath.Base(c)] {
				chosen[f] = true
			}
		}
		kinds, err := renderedKinds(root, env, all)
		if err != nil {
			return nil, err
		}
		var unknown []string
		for _, gk := range kinds {
			group := gk[:strings.LastIndex(gk, "/")]
			if f, ok := byKind[gk]; ok {
				chosen[f] = true
			} else if !builtIn(group) && !argoCD[gk] {
				unknown = append(unknown, gk)
			}
		}
		if len(unknown) > 0 {
			sort.Strings(unknown)
			return nil, fmt.Errorf("%s renders kinds no vendored CRD serves: %s (run scripts/vendor-crds for their component)", env, strings.Join(unknown, ", "))
		}
		for f := range chosen {
			lists[env] = append(lists[env], f)
		}
		sort.Strings(lists[env])
	}
	return lists, nil
}

// renderedKinds renders every target for env, four at a time, and returns the group/kinds they use
func renderedKinds(root, env string, all []string) ([]string, error) {
	var mu sync.Mutex
	seen := map[string]bool{}
	var firstErr error
	sem := make(chan struct{}, 4)
	var wg sync.WaitGroup
	for _, target := range all {
		wg.Add(1)
		go func(target string) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			out, err := render(root, target, env)
			var objs []object
			if err == nil {
				objs, err = documents(out)
			}
			mu.Lock()
			defer mu.Unlock()
			if err != nil {
				if firstErr == nil {
					firstErr = fmt.Errorf("%s (%s): %w", target, env, err)
				}
				return
			}
			for _, o := range objs {
				if o.APIVersion == "" || o.Kind == "" {
					continue
				}
				group := ""
				if i := strings.LastIndex(o.APIVersion, "/"); i >= 0 {
					group = o.APIVersion[:i]
				}
				seen[group+"/"+o.Kind] = true
			}
		}(target)
	}
	wg.Wait()
	if firstErr != nil {
		return nil, firstErr
	}
	var kinds []string
	for gk := range seen {
		kinds = append(kinds, gk)
	}
	sort.Strings(kinds)
	return kinds, nil
}

func path(root, env string) string {
	return filepath.Join(root, "system", "crds", "environments", env+".txt")
}

func content(list []string) []byte {
	return []byte(header + strings.Join(list, "\n") + "\n")
}

// Write writes every environment's list
func Write(root string) error {
	lists, err := Lists(root)
	if err != nil {
		return err
	}
	for _, env := range Environments {
		if err := os.MkdirAll(filepath.Dir(path(root, env)), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path(root, env), content(lists[env]), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Check fails, naming them, when an environment's list differs from what Write would write
func Check(root string) error {
	lists, err := Lists(root)
	if err != nil {
		return err
	}
	var stale []string
	for _, env := range Environments {
		raw, err := os.ReadFile(path(root, env))
		if err != nil || !bytes.Equal(raw, content(lists[env])) {
			stale = append(stale, env)
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("system/crds/environments out of date for %s: run lab crds generate", strings.Join(stale, ", "))
	}
	return nil
}
